package com.cbms.config;

import org.springframework.context.annotation.Configuration;
import org.springframework.web.servlet.config.annotation.InterceptorRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

@Configuration
public class ApplicationActivityAuditMvcConfig implements WebMvcConfigurer {
    private final ApplicationActivityAuditInterceptor interceptor;

    public ApplicationActivityAuditMvcConfig(ApplicationActivityAuditInterceptor interceptor) {
        this.interceptor = interceptor;
    }

    @Override
    public void addInterceptors(InterceptorRegistry registry) {
        registry.addInterceptor(interceptor).addPathPatterns("/api/**");
    }
}
